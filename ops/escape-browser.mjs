import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createApp } from '../server/app.mjs';
import { EscapeWorld } from '../src/escape/world.ts';
// Optional QA tooling: install Playwright separately or supply PLAYWRIGHT_MODULE.
// Always runs a separate headless profile with software rendering, never user tabs.
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE ?? 'playwright');
const output = path.resolve(process.env.ESCAPE_QA_DIR ?? '.local/escape-3d-qa');
await fs.mkdir(output, { recursive: true });
const server = createApp({distDir:fileURLToPath(new URL('../dist/', import.meta.url))}).listen(0,'127.0.0.1');
await new Promise(r=>server.once('listening',r));
const base=`http://127.0.0.1:${server.address().port}`;
let browser;
const errors=[];
try {
  browser=await chromium.launch({executablePath:process.env.CHROMIUM_PATH,headless:true,args:['--disable-gpu','--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader','--renderer-process-limit=1','--disable-background-networking']});
  const context=await browser.newContext({viewport:{width:900,height:650}, serviceWorkers:'allow'});
  const page=await context.newPage();
  page.on('pageerror',e=>errors.push(e.message));
  page.on('console',m=>{if(m.type()==='error') errors.push(m.text());});
  await page.goto(base); console.log('home'); await page.locator('#extreme').click(); await page.locator('#escape-new').click();
  await page.locator('#escape-panel[hidden]').waitFor({timeout:30000,state:'attached'}); console.log('3d-ready');
  await page.keyboard.press('Escape');
  await page.screenshot({path:path.join(output, 'pause.png')});
  await page.locator('#escape-resume').click();
  await page.keyboard.press('PageUp');
  await page.keyboard.down('PageUp'); await new Promise(r=>setTimeout(r,250)); await page.keyboard.up('PageUp');
  await page.screenshot({path:path.join(output, 'start.png')});
  await page.keyboard.press('Escape'); await page.locator('#escape-exit').click();
  const current=JSON.parse(await page.evaluate(()=>localStorage.getItem('nwaxz-escape-session-v1')));
  if(!(current.player.pitch>0)) throw new Error('vertical look did not save');
  const standing = new EscapeWorld();
  Object.assign(standing.data.player,{x:3.5,z:5.5,angle:0,pitch:0});
  Object.assign(standing.data.hunter,{x:5.8,z:5.5,angle:Math.PI});
  await page.evaluate(save=>localStorage.setItem('nwaxz-escape-session-v1',JSON.stringify(save)),standing.snapshot());
  await page.reload(); await page.locator('#extreme').click(); await page.locator('#escape-continue').click();
  await page.locator('#escape-panel[hidden]').waitFor({state:'attached',timeout:30000});
  await new Promise(r=>setTimeout(r,350));
  await page.screenshot({path:path.join(output,'original-frog.png')});
  if(await page.locator('#escape-stick').isVisible()) throw new Error('desktop joystick should be hidden');
  if(await page.locator('#escape-goal').count()) throw new Error('objective should appear only in pause journal');
  await page.keyboard.press('Escape'); await page.locator('#escape-exit').click();
  const caught=new EscapeWorld(); caught.capture();
  await page.evaluate(save=>localStorage.setItem('nwaxz-escape-session-v1',JSON.stringify(save)),caught.snapshot());
  await page.reload(); await page.locator('#extreme').click(); await page.locator('#escape-continue').click();
  await page.locator('.capture-active').waitFor({timeout:60000});
  await page.screenshot({path:path.join(output, 'laugh.png')});
  const firstLaugh=await page.locator('#escape-view').screenshot();
  await new Promise(r=>setTimeout(r,850));
  const nextLaugh=await page.locator('#escape-view').screenshot();
  if(firstLaugh.equals(nextLaugh)) throw new Error('Original-art belly laugh is frozen');
  await fs.writeFile(path.join(output,'laugh-loop.png'),nextLaugh);
  await page.locator('#escape-next').click(); await page.keyboard.press('Escape');
  const save=JSON.parse(await page.evaluate(()=>localStorage.getItem('nwaxz-escape-session-v1')));
  if(save.phase!=='playing'||save.captures!==1) throw new Error('next night failed');
  await page.locator('#escape-exit').click();
  const hiding = new EscapeWorld();
  Object.assign(hiding.data.player,{x:5.5,z:3.5,angle:-Math.PI/2});
  hiding.interact();
  await page.evaluate(save=>localStorage.setItem('nwaxz-escape-session-v1',JSON.stringify(save)),hiding.snapshot());
  await page.locator('#extreme').click(); await page.locator('#escape-continue').click();
  await page.locator('#escape-panel[hidden]').waitFor({state:'attached',timeout:30000});
  await page.screenshot({path:path.join(output,'cabinet.png')});
  await page.keyboard.press('e'); await page.keyboard.press('Escape');
  const leaving=JSON.parse(await page.evaluate(()=>localStorage.getItem('nwaxz-escape-session-v1')));
  if(leaving.hidden||leaving.player.z!==3.5) throw new Error('cabinet exit failed');
  const downloadEvent=page.waitForEvent('download'); await page.locator('#escape-backup').click();
  const download=await downloadEvent;
  const backup=await fs.readFile(await download.path(),'utf8');
  if(JSON.stringify(JSON.parse(backup).session)!==JSON.stringify(leaving)) throw new Error('backup differs from paused session');
  await page.locator('#escape-exit').click(); await page.locator('#extreme').click();
  await page.locator('#escape-import').setInputFiles({name:'escape-backup.json',mimeType:'application/json',buffer:Buffer.from(backup)});
  await page.waitForFunction(()=>document.querySelector('.escape-storage')?.textContent.includes('逃生存档已导入'));
  const imported=JSON.parse(await page.evaluate(()=>localStorage.getItem('nwaxz-escape-session-v1')));
  if(JSON.stringify(imported)!==JSON.stringify(leaving)) throw new Error('import changed saved session');
  await page.locator('#escape-intro-exit').click();
  const mobile=await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true,serviceWorkers:'allow'});
  const phone=await mobile.newPage();
  phone.on('pageerror',e=>errors.push('mobile: '+e.message));
  phone.on('console',m=>{if(m.type()==='error') errors.push('mobile: '+m.text());});
  await phone.goto(base); await phone.locator('#extreme').tap(); await phone.locator('#escape-new').tap();
  await phone.locator('#escape-panel[hidden]').waitFor({timeout:30000,state:'attached'});
  const cdp=await mobile.newCDPSession(phone), stick=await phone.locator('#escape-stick').boundingBox();
  const sx=stick.x+stick.width/2,sy=stick.y+stick.height/2;
  await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{x:sx,y:sy,id:1}]});
  await cdp.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[{x:sx,y:sy-30,id:1}]});
  await new Promise(r=>setTimeout(r,200));
  await cdp.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]});
  await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{x:300,y:320,id:2}]});
  await cdp.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[{x:345,y:285,id:2}]});
  await cdp.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]});
  await phone.screenshot({path:path.join(output, 'mobile.png')});
  const controlsOverlap=await phone.evaluate(()=>{
    const slots=[...document.querySelectorAll('.escape-slot')].map(e=>e.getBoundingClientRect());
    const controls=[...document.querySelectorAll('.escape-actions button,#escape-stick')].map(e=>e.getBoundingClientRect());
    return slots.some(s=>controls.some(c=>s.width&&c.width&&s.left<c.right&&s.right>c.left&&s.top<c.bottom&&s.bottom>c.top));
  });
  if(controlsOverlap) throw new Error('mobile inventory overlaps movement/action controls');
  await phone.locator('#escape-pause').tap();
  const mobileSave=JSON.parse(await phone.evaluate(()=>localStorage.getItem('nwaxz-escape-session-v1')));
  if(mobileSave.player.z>=5.5||mobileSave.player.pitch<=0) throw new Error('touch move/look failed');
  const pauseBefore=await phone.locator('#escape-view').screenshot();
  await new Promise(r=>setTimeout(r,160));
  if(!pauseBefore.equals(await phone.locator('#escape-view').screenshot())) throw new Error('pause did not freeze 3D');
  await phone.locator('#escape-exit').tap();
  await phone.evaluate(async()=>{await navigator.serviceWorker.ready;});
  await phone.waitForFunction(()=>!!navigator.serviceWorker.controller);
  const cached=await phone.evaluate(async()=>{let results=[]; for(const n of ['models/escape-props-v1.glb','character/haunted-frog-v1.webp','character/haunted-frog-actions-v2.webp','ui/escape-map-atlas-v1.webp'])results.push(!!await caches.match('/assets/'+n,{ignoreSearch:true}));return results;});
  if(!cached.every(Boolean)) throw new Error('3D models absent from offline cache');
  await mobile.setOffline(true); await phone.reload();
  await phone.locator('#extreme').tap(); await phone.locator('#escape-continue').tap();
  await phone.locator('#escape-panel[hidden]').waitFor({timeout:30000,state:'attached'});
  await phone.locator('#escape-pause').tap();
  await phone.screenshot({path:path.join(output, 'offline.png')});
  await mobile.close();
  await context.close();
  console.log(JSON.stringify({base, errors, pitch:current.player.pitch, nextNight:save.phase, mobileSave, cached, offline:true}));
  if(errors.length) process.exitCode=1;
} catch(e){console.error(e);console.error(JSON.stringify(errors));process.exitCode=1;} finally {await browser?.close();await new Promise(r=>server.close(r));}
