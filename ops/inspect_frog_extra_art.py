"""Read native PNG alpha bounds; emit metadata without modifying image bytes."""
from pathlib import Path
from collections import deque
from hashlib import sha256
import json
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
KINDS = {"directionStalk": "stalk-a", "directionStalkB": "stalk-b", "directionSearch": "listen", "directionAttack": "grab", "directionLaugh": "laugh"}
def silhouette(alpha):
    w, h = alpha.size
    pixels = bytearray(alpha.point(lambda a: int(a >= 64)).tobytes())
    best = None
    for start, value in enumerate(pixels):
        if not value: continue
        queue = deque([start]); pixels[start] = 0
        n, left, top, right, foot = 0, w, h, 0, 0
        while queue:
            p = queue.popleft(); x, y = p % w, p // w
            n += 1; left, top, right, foot = min(left, x), min(top, y), max(right, x+1), max(foot, y+1)
            for xx, yy in ((x-1,y),(x+1,y),(x,y-1),(x,y+1)):
                if 0 <= xx < w and 0 <= yy < h and pixels[yy*w+xx]:
                    pixels[yy*w+xx] = 0; queue.append(yy*w+xx)
        if best is None or n > best[0]: best = n, left, top, right, foot
    assert best and best[0] > w*h*.1, "Missing figure"
    return best[1:]

data = {}
for key, name in KINDS.items():
    relative = "assets/character/haunted-frog-extra-v3/"+name+".png"
    file = ROOT/"public"/relative; raw = file.read_bytes()
    image = Image.open(file); assert image.mode == "RGBA"
    width, height = image.size; alpha = image.getchannel("A")
    assert alpha.getextrema() == (0,255)
    frames = []
    for row in range(2):
        for col in range(4):
            # Native 1774x887 has fractional grid boundaries. Round boundaries
            # for analysis; retain original pixels and exact measured UV bounds.
            cx, cy, ex, ey = round(col*width/4), round(row*height/2), round((col+1)*width/4), round((row+1)*height/2)
            left, top, right, foot = silhouette(alpha.crop((cx,cy,ex,ey)))
            x, y, end, bottom = max(cx,cx+left-3), max(cy,cy+top-3), min(ex,cx+right+3), min(ey,cy+foot+3)
            frames.append(dict(x=x,y=y,width=end-x,height=bottom-y,ground=bottom-(cy+foot)))
    data[key] = dict(url="/"+relative,width=width,height=height,bytes=len(raw),sha256=sha256(raw).hexdigest(),frames=frames)
text = "// Native PNG alpha/foot bounds; generated by ops/inspect_frog_extra_art.py.\n"
text += "export const FROG_EXTRA_ART = "+json.dumps(data,indent=2)+" as const;\n"
(ROOT/"src/escape/extra-art.ts").write_text(text,encoding="utf8",newline="\n")
manifest = dict(generator="built-in imagegen",columns=4,rows=2,directions=["front","front-left","left","back-left","back","back-right","right","front-right"],assets=data)
(ROOT/"public/assets/character/haunted-frog-extra-v3/manifest.json").write_text(json.dumps(manifest,indent=2)+"\n",encoding="utf8",newline="\n")
print(json.dumps({k:dict(width=v['width'],height=v['height'],frames=len(v['frames']),bytes=v['bytes']) for k,v in data.items()}))
